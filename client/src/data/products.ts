export function normalizeText(s: string) {
  return s.toLowerCase().replace(/ё/g, 'е').replace(/[^a-zа-я0-9%,.\s]/g, ' ').replace(/\s+/g, ' ').trim();
}

/** Простой поиск: все слова запроса должны встречаться (по началу слов) */
export function searchProducts<T extends { name: string }>(list: T[], query: string, limit = 30): T[] {
  const q = normalizeText(query);
  if (!q) return list.slice(0, limit);
  const words = q.split(' ').filter(Boolean);
  const scored: { item: T; score: number }[] = [];
  for (const item of list) {
    const name = normalizeText(item.name);
    const nameWords = name.split(' ');
    let score = 0;
    let ok = true;
    for (const w of words) {
      const stem = w.length > 4 ? w.slice(0, w.length - 1) : w;
      if (nameWords.some((nw) => nw.startsWith(stem))) score += 2;
      else if (name.includes(stem)) score += 1;
      else {
        ok = false;
        break;
      }
    }
    if (ok) scored.push({ item, score: score - name.length / 100 });
  }
  return scored.sort((a, b) => b.score - a.score).slice(0, limit).map((s) => s.item);
}
