export function modeInstruction(mode: ChatMode, targetDays?: string[]) {
  switch (mode) {
    case 'plan': {
      const list = (targetDays || []).map((d) => `${d} (${fmtShort(d)})`).join(', ');
      return `\n\n[РЕЖИМ: ПЛАН] Составь распорядок на дни: ${list}. Верни действие "plan" с replace:true для КАЖДОГО из этих дней (даже если день пустой — items: []). Для сегодняшнего дня планируй только начиная с поля from. Старые дела ИИ (old) будут удалены — можешь переставить их заново, если они всё ещё нужны.`;
    }
    case 'tutor':
      return '\n\n[РЕЖИМ: РЕПЕТИТОР] Выше — сообщение о занятии с репетитором (из переписки). Найди дату и время и добавь занятие действием add_event (kind "tutor", fixed true). Если длительность не указана — используй {репетитор}. Если дата неоднозначна — выбери ближайшую подходящую и скажи об этом в reply. Если занятие пересекается с парой — предупреди.';
    case 'review':
      return '\n\n[РЕЖИМ: ИТОГИ ДНЯ] Оцени, как прошёл день (todayItems: st — done/skipped/planned, питание food). Похвали за сделанное, мягко — без упрёков — отметь, что не вышло, и дай 1–2 совета на завтра. Можешь начислить бонус (bonus, 0–30 монет) за реально хороший день. Если что-то стоит перенести на завтра — предложи plan с replace:false.';
    case 'decompose':
      return '\n\n[РЕЖИМ: ЦЕЛЬ] Разбей цель из поля goal: предложи 2–4 подцели следующего горизонта (add_goal с parent) и 3–6 конкретных задач на ближайшие 1–2 недели (add_task с goal), с оценкой времени и наградой. Учитывай контекст цели. Не дублируй уже существующие подцели и задачи.';
    default:
      return '';
  }
}

